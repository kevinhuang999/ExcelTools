"""
生成 ExcelTools 各按钮的测试数据（全虚构，零真实公司/客户/人名）。

用法：python _generate_samples.py
产物：与本脚本同目录的 *.xlsx

设计约束（来自源码，改数据时必须守住）：
  1. 表头必须在第 1 行，数据从第 2 行开始 —— 所有工具都按表头行 1 / 数据行 2 起读。
  2. 数据必须连续，A 列每行都要有值 —— MyTools.GetRealRows 遇到 A/B/D/F/H 全空的行会把行数截断。
  3. 单元格里不能出现字面量 "NULL" —— ClearSpecialSymbols 会把它替换成空。
  4. 拆分工作表的拆分值必须能当工作表名 —— ≤31 字符，不含 : \\ / ? * [ ]。
  5. 累计去重计数的输出列必须在数据区右侧之外 —— 本样本数据到 D 列，输出用 Z。

注意：不要用 ws.append()，openpyxl 3.1.5 里读一次 ws["A1"] 就会把 _current_row 推高，
append 会把表头写到第 2 行。这里一律用 ws.cell(row=, column=) 显式落位。
"""
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

OUT = Path(__file__).resolve().parent

HEADER_FONT = Font(bold=True, color="FFFFFF")
HEADER_FILL = PatternFill("solid", fgColor="4472C4")
HEADER_ALIGN = Alignment(horizontal="center", vertical="center")


def build_file(filename, sheets, active=0):
    """sheets: [(标题, 表头, 数据行列表), ...]"""
    wb = Workbook()
    for i, (title, header, rows) in enumerate(sheets):
        for row in rows:
            assert len(row) == len(header), \
                f"{filename}/{title} 列数不符：表头 {len(header)} 列，数据 {len(row)} 列 → {row}"
        ws = wb.active if i == 0 else wb.create_sheet()
        ws.title = title

        for c, value in enumerate(header, 1):
            ws.cell(row=1, column=c, value=value)
        for r, row in enumerate(rows, 2):
            for c, value in enumerate(row, 1):
                if value is None or value == "":
                    continue
                ws.cell(row=r, column=c, value=value)

        for c in range(1, len(header) + 1):
            cell = ws.cell(row=1, column=c)
            cell.font = HEADER_FONT
            cell.fill = HEADER_FILL
            cell.alignment = HEADER_ALIGN

        ws.freeze_panes = "A2"
        ws.row_dimensions[1].height = 22

        for c in range(1, len(header) + 1):
            width = len(str(header[c - 1]))
            for row in rows:
                if c - 1 < len(row):
                    width = max(width, len(str(row[c - 1])))
            ws.column_dimensions[get_column_letter(c)].width = min(max(10, width * 1.9 + 2), 34)

    wb.active = active
    wb.save(OUT / filename)


